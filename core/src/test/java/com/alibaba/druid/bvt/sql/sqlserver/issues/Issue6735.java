package com.alibaba.druid.bvt.sql.sqlserver.issues;

import com.alibaba.druid.DbType;
import com.alibaba.druid.sql.SQLUtils;
import com.alibaba.druid.sql.ast.SQLStatement;
import com.alibaba.druid.sql.ast.statement.SQLSelectOrderByItem;
import com.alibaba.druid.sql.ast.statement.SQLSelectQueryBlock;
import com.alibaba.druid.sql.ast.statement.SQLSelectStatement;
import com.alibaba.druid.sql.visitor.ParameterizedOutputVisitorUtils;
import org.junit.jupiter.api.Test;

import java.util.List;

import static org.junit.jupiter.api.Assertions.assertEquals;

/**
 * Fix SQL Server ORDER BY on a variable (e.g. {@code @@version}) followed by OFFSET ... FETCH,
 * as generated by Hibernate 6 for paginated queries without an explicit ORDER BY.
 *
 * @see <a href="https://github.com/alibaba/druid/issues/6735">Issue #6735</a>
 */
public class Issue6735 {
    @Test
    public void test_order_by_global_variable_offset_literal() {
        String sql = "select a from t order by @@version offset 0 rows fetch first ? rows only";
        SQLSelectQueryBlock queryBlock = parseQueryBlock(sql);

        List<SQLSelectOrderByItem> items = queryBlock.getOrderBy().getItems();
        assertEquals(1, items.size());
        assertEquals("@@version", items.get(0).getExpr().toString());
        assertEquals("SELECT a\n"
                + "FROM t\n"
                + "ORDER BY @@version\n"
                + "OFFSET 0 ROWS FETCH NEXT ? ROWS ONLY", queryBlock.getParent().toString());
    }

    @Test
    public void test_order_by_global_variable_offset_placeholder() {
        String sql = "select a from t order by @@version offset ? rows fetch next ? rows only";
        SQLSelectQueryBlock queryBlock = parseQueryBlock(sql);

        assertEquals(1, queryBlock.getOrderBy().getItems().size());
        assertEquals("SELECT a\n"
                + "FROM t\n"
                + "ORDER BY @@version\n"
                + "OFFSET ? ROWS FETCH NEXT ? ROWS ONLY", queryBlock.getParent().toString());
    }

    @Test
    public void test_order_by_local_variable_offset() {
        String sql = "select a from t order by a, @v desc offset 10 rows fetch next 20 rows only";
        SQLSelectQueryBlock queryBlock = parseQueryBlock(sql);

        assertEquals(2, queryBlock.getOrderBy().getItems().size());
        assertEquals("SELECT a\n"
                + "FROM t\n"
                + "ORDER BY a, @v DESC\n"
                + "OFFSET 10 ROWS FETCH NEXT 20 ROWS ONLY", queryBlock.getParent().toString());
    }

    @Test
    public void test_parameterize_hibernate_pagination() {
        String sql = "select a from t where b = ? order by @@version offset 0 rows fetch first ? rows only";
        String parameterized = ParameterizedOutputVisitorUtils.parameterize(sql, DbType.sqlserver);
        assertEquals("SELECT a\n"
                + "FROM t\n"
                + "WHERE b = ?\n"
                + "ORDER BY @@version\n"
                + "OFFSET ? ROWS FETCH NEXT ? ROWS ONLY", parameterized);
    }

    private static SQLSelectQueryBlock parseQueryBlock(String sql) {
        List<SQLStatement> stmtList = SQLUtils.parseStatements(sql, DbType.sqlserver);
        assertEquals(1, stmtList.size());
        return ((SQLSelectStatement) stmtList.get(0)).getSelect().getQueryBlock();
    }
}
